"""E2.2b: consistency in a tied plane (Phase 02, gate G2.2; F-016).

G2.2 asks whether Gimbal identifies frames whose pooled factors tie, i.e. whether its error goes to
zero with the number of samples while pooled-factor frames do not. At the fixed 800-step horizon of
E2.2, very long memories cannot show this: the warm-start frame comes from pooled factors (wrong in
tied planes), and with the bias-corrected schedule its weight decays only like T_w / t when the
memory exceeds the horizon (Remark 5.6). This experiment lengthens the horizon instead, with each
method's memory matched to it.

Design: the E2.2 tie cell (gamma = 0.5, s = 1, 32x48, tied row sums), seeds 10-14; horizons
T in {800, 4000, 16000}; Gimbal at alpha = 4/T and pooled-factor eigenvectors (exact, every step)
at beta = 1 - 4/T (both average over about T/2 samples); SOAP for reference at the same beta.
Score: frame KL averaged over the last 10% of steps.

Usage: python experiments/phase2/e22b_tie_consistency.py [--workers 4] [--tag _c013]
(``--tag`` names the outputs of a re-run after a change of the default; earlier outputs are kept.)
"""

from __future__ import annotations

import argparse
import json
import multiprocessing as mp
import pathlib
import time
import zlib

import numpy as np
import torch
from common import KRDStream, frame_trace, make_variances, rand_orth

RESULTS = pathlib.Path(__file__).parent / "results"
CFG = dict(gamma=0.5, slope=1.0, shape=(32, 48), tie=True, nu=None, drift=0.0)
HORIZONS = (800, 4000, 16000)
METHODS = ("gimbal", "gimbal_k4", "pooled_eigh", "soap")  # gimbal_k4: the default since C-012


def run(args) -> dict:
    method, horizon, seed = args
    torch.set_num_threads(1)
    cell_id = zlib.crc32(json.dumps(CFG, default=str, sort_keys=True).encode()) % 100_003
    rng = np.random.default_rng(1000 * seed + cell_id)  # the same arrays as E2.2 for these seeds
    m, n = CFG["shape"]
    d = make_variances(m, n, CFG["gamma"], CFG["slope"], rng, tie=True)
    ql, qr = rand_orth(m, rng), rand_orth(n, rng)
    stream = KRDStream(ql.copy(), qr.copy(), d, rng)
    grads = [g for _, g in zip(range(horizon), stream, strict=False)]
    mem = 4.0 / horizon if method.startswith("gimbal") else 1.0 - 4.0 / horizon
    trace = frame_trace(method, mem, grads, ql, qr, d, every=10)
    tail = trace[-max(1, len(trace) // 10):]
    return {"method": method, "horizon": horizon, "seed": seed, "memory": mem,
            "kl_tail": float(np.mean(tail)), "kl_trace_every10": trace.tolist()}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--tag", default="", help="suffix of the output files")
    args = parser.parse_args()
    jobs = [(m, h, s) for h in sorted(HORIZONS, reverse=True) for m in METHODS
            for s in range(10, 15)]
    t0 = time.time()
    with mp.Pool(args.workers) as pool:
        rows = pool.map(run, jobs, chunksize=1)
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / f"e22b_tie_consistency{args.tag}.jsonl").write_text(
        "\n".join(json.dumps(r) for r in rows))
    table = {(r["method"], r["horizon"]): [] for r in rows}
    for r in rows:
        table[(r["method"], r["horizon"])].append(r["kl_tail"])
    lines = ["# E2.2b consistency in a tied plane (generated by e22b_tie_consistency.py)", "",
             "Tie cell γ = 0.5, s = 1, 32×48, seeds 10–14; memory matched to the horizon T "
             "(Gimbal α = 4/T, factor EMAs β = 1 − 4/T); mean frame KL over the last 10% of "
             f"steps; {time.time() - t0:.0f} s.", "",
             "| method | " + " | ".join(f"T = {h}" for h in HORIZONS)
             + " | ratio T=16000 / T=800 |",
             "|---" * (len(HORIZONS) + 2) + "|"]
    means = {}
    for method in METHODS:
        vals = [float(np.mean(table[(method, h)])) for h in HORIZONS]
        means[method] = vals
        lines.append(f"| {method} | " + " | ".join(f"{v:.2f}" for v in vals)
                     + f" | {vals[-1] / vals[0]:.3f} |")
    # consistency: Gimbal's error falls at least 4x from T = 800 to T = 16000 (theory: ~20x),
    # pooled factors' error falls less than 2x (no identification in the tied plane)
    p = means["pooled_eigh"]
    ok = p[2] >= p[0] / 2
    for ours in ("gimbal", "gimbal_k4"):
        g = means[ours]
        ok &= (g[0] > g[1] > g[2] and g[2] <= g[0] / 4
               and all(g[i] < p[i] for i in range(len(HORIZONS))))
    lines += ["", "G2.2 consistency clause (Gimbal, with k = 1 and k = 4, falls ≥ 4× and "
              "monotonically; pooled falls < 2×; Gimbal below pooled at every horizon): "
              f"**{ok}**"]
    (RESULTS / f"e22b_report{args.tag}.md").write_text("\n".join(lines))
    (RESULTS / f"e22b_gate{args.tag}.json").write_text(
        json.dumps({"G2.2_consistency": bool(ok)}, indent=1))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
