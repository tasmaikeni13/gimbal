"""E2.9: ablations of Gimbal's components and defaults on frame-estimation streams (Phase 02).

Each variant changes one setting of the default Gimbal and is run on representative E2.1–E2.3
cells with dedicated seeds (40-47), at a small grid of rotation rates (best rate per variant and
cell). The score is the E2.1 metric: time-averaged frame KL over the second half of the run.

Usage: python experiments/phase2/e29_ablations.py [--seeds 8] [--workers 4]
"""

from __future__ import annotations

import argparse
import json
import multiprocessing as mp
import pathlib
import time
import zlib
from collections import defaultdict

import numpy as np
import torch
from common import KRDStream, frame_kl, make_variances, rand_orth, wilcoxon_less

from gimbal.torch import Gimbal

RESULTS = pathlib.Path(__file__).parent / "results"

VARIANTS = {
    "default": {},
    "transport": dict(transport=True),
    "init_eigh": dict(init="eigh"),
    "init_identity": dict(init="identity"),
    "warm_20": dict(warm_start_steps=20),
    "warm_100": dict(warm_start_steps=100),
    "no_shrink": dict(flow_shrink=False),
    "adam_v": dict(flow_beta=None),
    "damping_3e-4": dict(damping=3e-4),
    "damping_3e-2": dict(damping=3e-2),
    "floor_1e-3": dict(floor=1e-3),
    "floor_1e-2": dict(floor=1e-2),
    "max_angle_0.05": dict(max_angle=0.05),
    "max_angle_1": dict(max_angle=1.0),
    "constant_rate": dict(rot_schedule="constant"),
    "k4": dict(frame_every=4),
    "k10": dict(frame_every=10),
    "polish_4": dict(polish_every=4),
}

CELLS = [
    dict(gamma=0.0, slope=0.5, shape=(32, 48), tie=False, nu=None, drift=0.0),
    dict(gamma=0.0, slope=1.5, shape=(32, 48), tie=False, nu=None, drift=0.0),
    dict(gamma=1.0, slope=1.0, shape=(32, 48), tie=False, nu=None, drift=0.0),
    dict(gamma=2.0, slope=0.5, shape=(32, 48), tie=False, nu=None, drift=0.0),
    dict(gamma=0.5, slope=1.0, shape=(32, 48), tie=True, nu=None, drift=0.0),
    dict(gamma=1.0, slope=1.0, shape=(32, 48), tie=False, nu=3.0, drift=0.0),
    dict(gamma=1.0, slope=1.0, shape=(32, 48), tie=False, nu=None, drift=3e-3),
]


def rates(cfg: dict) -> list[float]:
    return [0.02, 0.05, 0.1] if cfg["drift"] > 0 else [0.0025, 0.005, 0.01]


def run_cell(args: tuple[dict, int, int]) -> list[dict]:
    cfg, seed, steps = args
    torch.set_num_threads(1)
    cell_id = zlib.crc32(json.dumps(cfg, default=str, sort_keys=True).encode()) % 100_003
    rng = np.random.default_rng(1000 * seed + cell_id)
    m, n = cfg["shape"]
    d = make_variances(m, n, cfg["gamma"], cfg["slope"], rng, tie=cfg["tie"])
    ql, qr = rand_orth(m, rng), rand_orth(n, rng)
    stream = KRDStream(ql.copy(), qr.copy(), d, rng, nu=cfg["nu"], drift=cfg["drift"])
    grads, frames = [], []
    for _, g in zip(range(steps), stream, strict=False):
        grads.append(g)
        frames.append((stream.ql.copy(), stream.qr.copy()))
    true_frames = [(ql, qr)] + frames[:-1] if cfg["drift"] > 0 else [(ql, qr)] * steps
    rows = []
    for name, kw in VARIANTS.items():
        for rate in rates(cfg):
            p = torch.nn.Parameter(torch.zeros(m, n, dtype=torch.float64))
            opt = Gimbal([p], lr=0.0, rot_rate=rate, **kw)
            trace = []
            for t, g in enumerate(grads):
                p.grad = torch.from_numpy(g)
                opt.step()
                st = opt.state[p]
                trace.append(frame_kl(st["QL"].numpy(), st["QR"].numpy(), *true_frames[t], d))
            rows.append({**{k: (list(v) if isinstance(v, tuple) else v) for k, v in cfg.items()},
                         "seed": seed, "variant": name, "rate": rate,
                         "kl_second_half": float(np.mean(trace[steps // 2:]))})
    return rows


def cell_label(r: dict) -> str:
    s = f"γ={r['gamma']:g} s={r['slope']:g}"
    if r["tie"]:
        s += " tie"
    if r["nu"]:
        s += f" t(ν={r['nu']:g})"
    if r["drift"]:
        s += f" drift={r['drift']:g}"
    return s


def analyze(rows: list[dict]) -> str:
    score = defaultdict(lambda: defaultdict(lambda: defaultdict(dict)))
    for r in rows:
        score[cell_label(r)][r["variant"]][r["rate"]][r["seed"]] = r["kl_second_half"]
    lines = ["# E2.9 ablations (generated by e29_ablations.py)", "",
             "Mean frame KL (second half) at each variant's best rotation rate; the ratio is "
             "variant / default (geometric mean over seeds), `*` marks a one-sided paired Wilcoxon "
             "p < 0.05 for a difference from the default (either direction).", ""]
    cells = list(score)
    lines += ["| variant | " + " | ".join(cells) + " |", "|---" * (len(cells) + 1) + "|"]
    best = {}
    for c in cells:
        for v, by_rate in score[c].items():
            rate = min(by_rate, key=lambda a: np.mean(list(by_rate[a].values())))
            seeds = sorted(by_rate[rate])
            best[(c, v)] = np.array([by_rate[rate][s] for s in seeds])
    for v in VARIANTS:
        cells_txt = []
        for c in cells:
            x, base = best[(c, v)], best[(c, "default")]
            ratio = float(np.exp(np.mean(np.log(x) - np.log(base))))
            sig = v != "default" and min(wilcoxon_less(x, base), wilcoxon_less(base, x)) < 0.05
            cells_txt.append(f"{x.mean():.2f} ({ratio:.2f}{'*' if sig else ''})")
        lines.append(f"| {v} | " + " | ".join(cells_txt) + " |")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seeds", type=int, default=8)
    parser.add_argument("--steps", type=int, default=800)
    parser.add_argument("--workers", type=int, default=4)
    args = parser.parse_args()
    jobs = [(c, 40 + s, args.steps) for c in CELLS for s in range(args.seeds)]
    t0 = time.time()
    rows = []
    with mp.Pool(args.workers) as pool:
        for i, r in enumerate(pool.imap_unordered(run_cell, jobs)):
            rows += r
            if i % 8 == 0:
                print(f"{i + 1}/{len(jobs)} cells, {time.time() - t0:.0f}s", flush=True)
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "e29_ablations.jsonl").write_text("\n".join(json.dumps(r) for r in rows))
    report = analyze(rows)
    (RESULTS / "e29_report.md").write_text(report)
    print(report)


if __name__ == "__main__":
    main()
