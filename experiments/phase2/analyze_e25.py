"""Analysis of E2.5 (noisy quadratic optimization) and gate item G2.4.

For every configuration (gamma, noise level) each method runs at the learning rate selected on the
tuning seeds; the evaluation seeds are fresh and paired across methods. Gimbal is compared with
every peer (the oracle, Adam in the true frame, is a ceiling and not a peer) through the paired
difference of final losses: mean, percentile-bootstrap 95% interval, and the geometric-mean loss
ratio.

G2.4 (phases/02): in every configuration with gamma >= 1 Gimbal has the lowest mean final loss and
the interval of its difference to each peer excludes 0; elsewhere it is not significantly worse than
the best peer. Gimbal variants (``gimbal_*``) are ablations of ours and are not counted as peers.

Outputs are named after the run: ``--tag full`` is the run that found F-020 (evaluation seeds
100-111, before C-013), ``--tag full_c013`` (default) the confirmation of C-013 (seeds 300-311).

Usage: python experiments/phase2/analyze_e25.py [--tag full_c013]
"""

from __future__ import annotations

import argparse
import json
import pathlib
from collections import defaultdict

import numpy as np
from common import paired_bootstrap_ci

RESULTS = pathlib.Path(__file__).parent / "results"
ORACLE = "oracle"


def pooled_log_ratio(diffs: list[np.ndarray]) -> dict:
    """DerSimonian–Laird random-effects pooling of per-configuration mean paired log-ratios
    (configurations as studies; within-configuration standard error from the seeds)."""
    y = np.array([d.mean() for d in diffs])
    v = np.array([max(d.var(ddof=1) / len(d), 1e-12) for d in diffs])
    w = 1 / v
    fixed = np.sum(w * y) / np.sum(w)
    q = float(np.sum(w * (y - fixed) ** 2))
    k = len(y)
    tau2 = max(0.0, (q - (k - 1)) / (np.sum(w) - np.sum(w**2) / np.sum(w)))
    w_re = 1 / (v + tau2)
    mu = np.sum(w_re * y) / np.sum(w_re)
    se = np.sqrt(1 / np.sum(w_re))
    return {
        "factor": float(np.exp(mu)),
        "lo": float(np.exp(mu - 1.96 * se)),
        "hi": float(np.exp(mu + 1.96 * se)),
        "i2": float(max(0.0, (q - (k - 1)) / q)) if q > 0 else 0.0,
        "k": k,
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--tag", default="full_c013")
    args = parser.parse_args()
    rows = [
        json.loads(x)
        for x in (RESULTS / f"e25_eval_{args.tag}.jsonl").read_text().splitlines()
        if x.strip()
    ]
    selected = json.loads((RESULTS / f"e25_selected_lr_{args.tag}.json").read_text())
    loss = defaultdict(dict)  # (gamma, noise) -> method -> {seed: final loss}
    for r in rows:
        loss[(r["gamma"], r["noise"])].setdefault(r["method"], {})[r["seed"]] = r["final_loss"]
    report = [
        "# E2.5 noisy quadratic (generated by analyze_e25.py)",
        "",
        "Mean final loss over the evaluation seeds at each method's selected learning rate "
        "(`*`: selected LR on the grid edge). Lower is better.",
        "",
    ]
    methods = sorted(
        {m for cfg in loss.values() for m in cfg}, key=lambda m: (not m.startswith("gimbal"), m)
    )
    report += ["| γ | noise | " + " | ".join(methods) + " |", "|---" * (len(methods) + 2) + "|"]
    gate = {"configs": {}, "by_variant": {}}
    all_ok = True
    for (gamma, noise), by_method in sorted(loss.items()):
        cells = []
        for m in methods:
            vals = list(by_method.get(m, {}).values())
            edge = selected.get(f"{gamma}|{noise}|{m}", {}).get("at_grid_edge", False)
            cells.append(f"{np.mean(vals):.4g}{'*' if edge else ''}" if vals else "—")
        report.append(f"| {gamma:g} | {noise:g} | " + " | ".join(cells) + " |")
    # G2.4 for the default configuration (frame_every = 4 since C-012, "gimbal_k4") and, for the
    # record, for frame_every = 1 ("gimbal")
    for ours in ("gimbal_k4", "gimbal"):
        ours_ok = True
        configs = {}
        for (gamma, noise), by_method in sorted(loss.items()):
            g = by_method[ours]
            seeds = sorted(g)
            peers = [m for m in by_method if m != ORACLE and not m.startswith("gimbal")]
            means = {m: float(np.mean([by_method[m][s] for s in seeds])) for m in peers}
            best_peer = min(means, key=means.get)
            comparisons = {}
            for m in peers:
                d = np.array([g[s] - by_method[m][s] for s in seeds])
                ratio = np.array([np.log(g[s]) - np.log(by_method[m][s]) for s in seeds])
                mean, lo, hi = paired_bootstrap_ci(d)
                comparisons[m] = {
                    "mean_diff": mean,
                    "ci95": [lo, hi],
                    "geo_ratio": float(np.exp(ratio.mean())),
                }
            lowest = float(np.mean(list(g.values()))) < min(means.values())
            all_excl = all(c["ci95"][1] < 0 for c in comparisons.values())
            not_worse = comparisons[best_peer]["ci95"][0] <= 0
            ok = (lowest and all_excl) if gamma >= 1 else not_worse
            ours_ok &= ok
            configs[f"gamma={gamma:g},noise={noise:g}"] = {
                "mean": float(np.mean(list(g.values()))),
                "best_peer": best_peer,
                "lowest": lowest,
                "all_ci_exclude_0": all_excl,
                "not_worse_than_best": not_worse,
                "pass": ok,
                "vs_peer": comparisons,
            }
        gate["by_variant"][ours] = {"pass": bool(ours_ok), "configs": configs}
    gate["configs"] = gate["by_variant"]["gimbal_k4"]["configs"]
    all_ok = gate["by_variant"]["gimbal_k4"]["pass"]
    gate["G2.4_k1"] = gate["by_variant"]["gimbal"]["pass"]
    gate["G2.4"] = all_ok
    report += [
        "",
        "## Gimbal (default, frame_every = 4) minus peer (paired; negative = Gimbal better)",
        "",
    ]
    for cfg, c in gate["configs"].items():
        report.append(f"**{cfg}** — best peer {c['best_peer']}, pass: {c['pass']}")
        report.append("")
        for m, v in sorted(c["vs_peer"].items(), key=lambda kv: kv[1]["geo_ratio"]):
            report.append(
                f"* {m}: diff {v['mean_diff']:.4g} [{v['ci95'][0]:.4g}, "
                f"{v['ci95'][1]:.4g}], loss ratio {v['geo_ratio']:.3f}"
            )
        report.append("")
    # Random-effects summary across configurations (reported, not a gate item)
    peers = sorted(
        {
            m
            for by_method in loss.values()
            for m in by_method
            if m != ORACLE and not m.startswith("gimbal")
        }
    )
    gate["random_effects_loss_ratio"] = {}
    report += [
        "## Pooled across configurations (random effects)",
        "",
        "Geometric-mean final-loss ratio default / peer, DerSimonian–Laird pooling of the "
        "per-configuration mean paired log-ratios; < 1 means the default is better.",
        "",
        "| peer | pooled ratio | 95% CI | I² | configurations |",
        "|---|---|---|---|---|",
    ]
    for peer in peers:
        diffs = []
        for by_method in loss.values():
            g, q = by_method["gimbal_k4"], by_method[peer]
            diffs.append(np.array([np.log(g[s]) - np.log(q[s]) for s in sorted(g)]))
        r = pooled_log_ratio(diffs)
        gate["random_effects_loss_ratio"][peer] = r
        report.append(
            f"| {peer} | {r['factor']:.3f} | [{r['lo']:.3f}, {r['hi']:.3f}] | "
            f"{r['i2']:.2f} | {r['k']} |"
        )
    report.append("")
    # Frame statistics (C-013): the default (empirical-Bayes innovation) against the raw gradient
    # and the fully centered innovation, paired over the evaluation seeds.
    arms = ("gimbal_k4_nocenter", "gimbal_k4_center")
    if all(a in by_method for by_method in loss.values() for a in arms):
        report += [
            "## Frame statistics (C-013): default / ablation, paired loss ratio",
            "",
            "Geometric mean of the per-seed ratio, percentile-bootstrap 95% interval; < 1 "
            "means the default is better.",
            "",
            "| γ | noise | " + " | ".join(f"vs {a}" for a in arms) + " |",
            "|---" * (len(arms) + 2) + "|",
        ]
        gate["centering_ablation"] = {}
        for (gamma, noise), by_method in sorted(loss.items()):
            g = by_method["gimbal_k4"]
            seeds = sorted(g)
            cells, entry = [], {}
            for a in arms:
                diff = np.array([np.log(g[s]) - np.log(by_method[a][s]) for s in seeds])
                mean, lo, hi = paired_bootstrap_ci(diff)
                entry[a] = [float(np.exp(mean)), float(np.exp(lo)), float(np.exp(hi))]
                cells.append(f"{np.exp(mean):.3f} [{np.exp(lo):.3f}, {np.exp(hi):.3f}]")
            gate["centering_ablation"][f"gamma={gamma:g},noise={noise:g}"] = entry
            report.append(f"| {gamma:g} | {noise:g} | " + " | ".join(cells) + " |")
        report.append("")
    k1 = "pass" if gate["G2.4_k1"] else "fail"
    report += [
        "## Gate",
        "",
        f"G2.4 (default, frame_every = 4): **{'pass' if all_ok else 'fail'}**"
        f"; with frame_every = 1: **{k1}**",
        "",
    ]
    (RESULTS / f"e25_report_{args.tag}.md").write_text("\n".join(report))
    (RESULTS / f"e25_gate_{args.tag}.json").write_text(json.dumps(gate, indent=1))
    print("\n".join(report[: len(loss) + 6]))
    print(f"G2.4: {all_ok}")


if __name__ == "__main__":
    main()
