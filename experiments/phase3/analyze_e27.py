"""Analysis of E3.2 (formerly E2.7; small LM) and gate item G3.5 (formerly G2.6).

Reads ``results/lm/*.summary.json`` and the per-step logs. Stage A (seed 0, LR grid) selects one
LR per optimizer by final validation loss; Stage B adds seeds at that LR. Gimbal is compared with
every peer on the seeds both have at their selected LR: paired differences, one-sided paired
t-test (Holm-corrected across peers) and the "lower on every seed" criterion of the gate.

Usage: python experiments/phase3/analyze_e27.py [--tag TAG]
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

import numpy as np
import scipy.stats

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "phase2"))
from common import holm  # noqa: E402  (shared helpers in experiments/phase2)
from run_e27_sweep import GRIDS

RESULTS = pathlib.Path(__file__).parent / "results"


def load(tag: str) -> list[dict]:
    """Sweep runs with the given tag; run ids are ``{method}_lr{lr}_s{seed}{tag}``."""
    pattern = re.compile(r"^.+_lr[^_]+_s\d+" + re.escape(tag) + "$")
    rows = []
    for p in (RESULTS / "lm").glob("*.summary.json"):
        r = json.loads(p.read_text())
        if pattern.match(r["run_id"]):
            rows.append(r)
    return rows


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--tag", default="")
    args = parser.parse_args()
    rows = load(args.tag)
    report = ["# E3.2 small LM on FineWeb-Edu bytes (generated by analyze_e27.py)", ""]
    report += ["## Stage A: final validation loss by learning rate (seed 0)", "",
               "Initial grid of four learning rates per optimizer (factor 2), extended outward "
               "while the best one was on the edge (at most twice).", "",
               "| optimizer | learning rate: final validation loss | selected |", "|---|---|---|"]
    selected = {}
    for method in GRIDS:
        runs = sorted((x for x in rows if x["method"] == method and x["seed"] == 0),
                      key=lambda x: x["lr"])
        if not runs:
            continue
        cells = [f"{r['lr']:g}: {'div' if r['diverged'] else format(r['final_val_loss'], '.4f')}"
                 for r in runs]
        ok = [r for r in runs if not r["diverged"]]
        if not ok:
            report.append(f"| {method} | " + ", ".join(cells) + " | — |")
            continue
        best = min(ok, key=lambda r: r["final_val_loss"])["lr"]
        selected[method] = best
        edge = best in (runs[0]["lr"], runs[-1]["lr"])
        report.append(f"| {method} | " + ", ".join(cells)
                      + f" | {best:g}{' (edge)' if edge else ''} |")
    # Stage B
    per_seed = {m: {r["seed"]: r for r in rows if r["method"] == m and abs(r["lr"] - lr) < 1e-12}
                for m, lr in selected.items()}
    report += ["", "## Selected LR, all seeds: final validation loss", "",
               "| optimizer | lr | seeds | mean | per seed | wall s/run | optimizer s/run |",
               "|---|---|---|---|---|---|---|"]
    for m, by_seed in per_seed.items():
        if not by_seed:
            continue
        vals = [by_seed[s]["final_val_loss"] for s in sorted(by_seed)]
        wall = np.mean([by_seed[s]["wall_seconds"] for s in by_seed])
        opt_s = np.mean([by_seed[s]["optimizer_seconds"] for s in by_seed])
        report.append(f"| {m} | {selected[m]:g} | {len(vals)} | {np.mean(vals):.4f} | "
                      + ", ".join(f"{v:.4f}" for v in vals) + f" | {wall:.0f} | {opt_s:.0f} |")
    gate = {}
    for ours in ("gimbal", "gimbal_k4"):
        if ours not in per_seed:
            continue
        g_seeds = per_seed[ours]
        pvals, every_seed, diffs = {}, {}, {}
        for m, by_seed in per_seed.items():
            if m.startswith("gimbal"):  # variants of ours are not peers
                continue
            common_seeds = sorted(set(g_seeds) & set(by_seed))
            if len(common_seeds) < 2:
                continue
            d = np.array([g_seeds[s]["final_val_loss"] - by_seed[s]["final_val_loss"]
                          for s in common_seeds])
            diffs[m] = d.tolist()
            every_seed[m] = bool(np.all(d < 0))
            pvals[m] = float(scipy.stats.ttest_1samp(d, 0.0, alternative="less").pvalue)
        adj = holm(pvals)
        res = {"minus_peer_by_seed": diffs, "lower_on_every_seed": every_seed,
               "holm_p_one_sided": adj,
               "loss_criterion": bool(every_seed) and all(every_seed.values())}
        gate[ours] = res
        report += ["", f"## {ours} vs peers (paired by seed; negative = {ours} better)", "",
                   "```", json.dumps(res, indent=1), "```"]
    if "gimbal" in gate:
        gate["G3.5_loss"] = gate["gimbal"]["loss_criterion"]
    (RESULTS / "e27_report.md").write_text("\n".join(report))
    (RESULTS / "e27_gate.json").write_text(json.dumps(gate, indent=1))
    print("\n".join(report))


if __name__ == "__main__":
    main()
