"""G3.5 re-run after C-018 (F-027): the new Gimbal default against SOAP and AdamW on fresh seeds.

Gimbal's learning rate is re-selected with the original E3.2 budget (four rates, factor 2, edge
extension) on seed 20; then seeds 21 and 22 at the selected rate. SOAP and AdamW keep the rates
their own E3.2 Stage A selected (4e-3, 1e-3) and run on seeds 20-22 for the paired comparison.
Outputs ``results/lm/*_c018.*`` and ``results/g35_c018.{md,json}``.

Usage: python experiments/phase3/run_g35_c018.py --jobs 16
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys
from concurrent.futures import ThreadPoolExecutor

import numpy as np
import scipy.stats
from run_e27_sweep import run

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "phase2"))
from common import holm  # noqa: E402

HERE = pathlib.Path(__file__).parent
TAG = "_c018"
GRID = [1e-3, 2e-3, 4e-3, 8e-3]
FIXED_LR = {"soap": 4e-3, "adamw": 1e-3}
SEEDS = (20, 21, 22)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--jobs", type=int, default=16)
    args = parser.parse_args()
    one = lambda job: run(*job, 800, 1, TAG)  # noqa: E731
    with ThreadPoolExecutor(args.jobs) as pool:
        jobs = [("gimbal", lr, SEEDS[0]) for lr in GRID]
        jobs += [(m, lr, s) for m, lr in FIXED_LR.items() for s in SEEDS]
        results = list(pool.map(one, jobs))
        stage_a = {r["lr"]: r for r in results[:len(GRID)]}
        for _ in range(2):  # edge extension, as in E3.2
            ok = {lr: r for lr, r in stage_a.items() if not r["diverged"]}
            best = min(ok, key=lambda lr: ok[lr]["final_val_loss"])
            edge = best * 2 if best == max(stage_a) else best / 2 if best == min(stage_a) else None
            if edge is None:
                break
            stage_a[edge] = one(("gimbal", edge, SEEDS[0]))
        best = min((lr for lr, r in stage_a.items() if not r["diverged"]),
                   key=lambda lr: stage_a[lr]["final_val_loss"])
        list(pool.map(one, [("gimbal", best, s) for s in SEEDS[1:]]))
    loss = {}
    for m, lr in {"gimbal": best, **FIXED_LR}.items():
        loss[m] = [json.loads((HERE / "results" / "lm" /
                               f"{m}_lr{lr:g}_s{s}{TAG}.summary.json").read_text())
                   ["final_val_loss"] for s in SEEDS]
    diffs = {m: (np.array(loss["gimbal"]) - np.array(loss[m])).tolist() for m in FIXED_LR}
    pvals = {m: float(scipy.stats.ttest_1samp(d, 0.0, alternative="less").pvalue)
             for m, d in diffs.items()}
    adj = holm(pvals)
    every = {m: bool(np.all(np.array(d) < 0)) for m, d in diffs.items()}
    gate = {"gimbal_lr": best, "stage_a": {f"{lr:g}": r["final_val_loss"]
                                           for lr, r in sorted(stage_a.items())},
            "final_val_loss": loss, "gimbal_minus_peer": diffs, "lower_on_every_seed": every,
            "holm_p_one_sided": adj,
            "G3.5": bool(all(every[m] or adj[m] < 0.05 for m in FIXED_LR))}
    (HERE / "results" / "g35_c018.json").write_text(json.dumps(gate, indent=1))
    lines = ["# G3.5 re-run after C-018 (generated by run_g35_c018.py)", "",
             f"Seeds {SEEDS}; Gimbal (default since C-018: rot_rate 0.05, adaptive amortization) "
             f"at its re-selected learning rate {best:g}; SOAP and AdamW at their E3.2 rates.", "",
             "| optimizer | lr | per seed | mean |", "|---|---|---|---|"]
    for m, lr in {"gimbal": best, **FIXED_LR}.items():
        lines.append(f"| {m} | {lr:g} | " + ", ".join(f"{x:.4f}" for x in loss[m])
                     + f" | {np.mean(loss[m]):.4f} |")
    lines += ["", "```", json.dumps(gate, indent=1), "```"]
    (HERE / "results" / "g35_c018.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
