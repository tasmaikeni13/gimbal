"""Generate docs/performance.md from the JSON outputs in benchmarks/tpu/results (Phase 04, G4.4).

Every number in the document is read from a results file written by a benchmark script; this script
only formats them. Usage: python benchmarks/tpu/make_performance_doc.py
"""

from __future__ import annotations

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
RES = ROOT / "benchmarks" / "tpu" / "results"
OUT = ROOT / "docs" / "performance.md"

# Floating-point work of one optimizer update per device (multiply-adds), from the shapes of the
# 125M model and the bucket layout: per device 3 matrices of 768x2048 and 3 of 768x768.
RECT, SQ = (768, 2048), (768, 768)


def unit(shape: tuple[int, int]) -> float:
    m, n = shape
    return m * m * n + m * n * n  # one two-sided rotation, or one pair of factor products


def cube(shape: tuple[int, int]) -> float:
    m, n = shape
    return m**3 + n**3


def per_device(fn) -> float:
    return 3 * fn(RECT) + 3 * fn(SQ)


def load(name: str):
    path = RES / name
    return json.loads(path.read_text()) if path.exists() else None


def main() -> None:
    env = json.loads((ROOT / "runs" / "env.json").read_text())
    lines = [
        "# Performance on the TPU v4-32 slice (generated by "
        "`benchmarks/tpu/make_performance_doc.py`)",
        "",
        "## Setup",
        "",
        f"* {env['device_count']} × {env['device_kind']} ({env['process_count']} hosts × "
        f"{env['local_device_count']} chips), {env['hbm_bytes_per_device'] / 2**30:.1f} GiB "
        f"HBM per chip; JAX {env['jax']}, libtpu {env['libtpu']}, Python {env['python']} "
        "(`runs/env.json`, `scripts/tpu/env_check.py`).",
        "* Model and batch of the confirmatory runs: 123.6M parameters, 240 × 1024 tokens per "
        "step, bfloat16 compute, float32 master weights and optimizer state "
        "(`configs/base_125m.yaml`).",
        "* One mesh axis over all 16 chips: the batch is sharded, parameters are replicated, "
        "and the optimizer state of each bucket of same-shaped matrices (48 × 768×768 and "
        "36 → 48 padded × 768×2048) is sharded along the bucket axis (ZeRO-1). Gradients are "
        "reduced in float32; parameter increments are all-gathered "
        "(`src/gimbal/jax/distributed.py`).",
        "* Every optimizer gets the same layout, batching, sharding and precision policy: all "
        "optimizer matrix products at `Precision.HIGHEST` (float32).",
        "",
    ]
    att = load("attention.json")
    if att:
        lines += [
            "## Attention (gradient step of the full model, median of 20 calls)",
            "",
            "| implementation | tiles (q, k, batch) | seconds |",
            "|---|---|---|",
        ]
        for k, v in att.items():
            kind, q, kk, b = k.split("_")
            val = f"{v:.4f}" if isinstance(v, float) else "fails (VMEM)"
            lines.append(f"| {kind} | {q[1:]}, {kk[1:]}, {b[1:]} | {val} |")
        lines += [
            "",
            "Splash attention needs a head dimension that is a multiple of 128 (the "
            "model has 64). The Pallas flash-attention kernel with 512 × 512 tiles is used "
            "for all runs.",
            "",
        ]
    var = {
        k: load(f"variants{s}.json")
        for k, s in (
            ("scan, flash", ""),
            ("scan, xla", "_attention_xla"),
            ("unrolled, flash", "_scan_layers_false"),
            ("unrolled, xla", "_attention_xla__scan_layers_false"),
        )
    }
    if any(var.values()):
        lines += [
            "## Gradient step: layers and attention (seconds, median of 20 calls)",
            "",
            "| layers, attention | forward | forward + backward (local) |",
            "|---|---|---|",
        ]
        for k, v in var.items():
            if v:
                lines.append(f"| {k} | {v['forward_only']:.4f} | {v['fwd_bwd_local']:.4f} |")
        base = var["scan, flash"]
        if base and "fwd_bwd_reduce_scatter" in base:
            lines += [
                "",
                f"With the float32 gradient reduction the step takes "
                f"{base['fwd_bwd_reduce_scatter']:.4f} s (scan layers); bfloat16 logits "
                f"would save {base['fwd_bwd_local'] - base['fwd_bwd_local_bf16_logits']:.4f}"
                f" s and are not used; the output head and loss cost "
                f"{base['fwd_bwd_local'] - base['fwd_bwd_local_no_head']:.4f} s. Unrolled "
                "layers with flash attention are used for all runs.",
            ]
        lines.append("")
    col = load("collectives.json")
    if col:
        lines += [
            "## Collectives on a 48 × 768 × 2048 array (seconds, median)",
            "",
            "| collective | float32 | bfloat16 | HLO op |",
            "|---|---|---|---|",
        ]
        for name in ("psum", "psum_scatter_tiled", "psum_scatter_untiled", "all_gather"):
            f32, b16 = col.get(f"{name}_float32"), col.get(f"{name}_bfloat16")
            if f32:
                lines.append(
                    f"| {name} | {f32['seconds']:.4f} | {b16['seconds']:.4f} | "
                    f"{', '.join(f32['hlo'])} |"
                )
        lines += [
            "",
            "On this runtime XLA lowers a reduce-scatter to an all-reduce of the same "
            "cost. Gathering bfloat16 instead of float32 would halve the parameter "
            "all-gather for every optimizer alike; it is not used.",
            "",
        ]
    st = load("step_times.json")
    if st:
        soap = st["soap"]["steady_state_s"]
        lines += [
            "## Steady-state step time (gate G4.2)",
            "",
            "Definition fixed before measurement (C-017): median over the 20-step blocks of "
            "steps 200–400 of the mean step time within a block, from 400-step runs at the "
            "confirmatory configuration with real data (`scripts/tpu/time_variants.sh`, "
            "`benchmarks/tpu/step_times.py`, logs in `runs/timing/`).",
            "",
            "| run | optimizer settings | steady state (ms) | vs SOAP | median of single "
            "steps (ms) |",
            "|---|---|---|---|---|",
        ]
        for name, v in st.items():
            mc = v["matrix_config"]
            desc = ""
            if v["optimizer"] == "gimbal":
                desc = (
                    f"α = {mc['rot_rate']}, frame_every = {mc['frame_every']}, "
                    f"{mc.get('frame_schedule', 'fixed')}"
                )
            lines.append(
                f"| {name} | {desc} | {1e3 * v['steady_state_s']:.2f} | "
                f"{100 * (v['steady_state_s'] / soap - 1):+.1f}% | "
                f"{1e3 * v['per_step_median_s']:.2f} |"
            )
        gim = st.get("gimbal_adapt_a05", {}).get("steady_state_s")
        if gim:
            verdict = "passes" if gim <= soap else "fails"
            lines += [
                "",
                f"G4.2 for the default since C-018 (`gimbal_adapt_a05`): "
                f"{1e3 * gim:.2f} ms vs SOAP {1e3 * soap:.2f} ms, {verdict} "
                f"({100 * (gim / soap - 1):+.1f}%). The gap is the frame move: on the "
                "2048-dimensional side the retraction, the Newton–Schulz polish and the "
                "orthogonality check are float32 products at full precision, which the TPU "
                "executes at a fraction of its bfloat16 rate, and the polish needs 3–4 "
                "iterations per move because the per-move rotation of a 2048-dimensional "
                "frame is large in spectral norm. Phase 04's repair order was followed "
                "(batching, amortized retraction); lower-precision rotations would shrink "
                "SOAP's and Gimbal's costs alike and cannot close the gap (estimated "
                "0.2 ms). The result is reported as a wall-clock loss.",
                "",
            ]
    flops = {
        "SOAP plain step": 3 * per_device(unit),
        "Gimbal plain step": 3 * per_device(unit),
        "Gimbal frame move (extra, 3.5 polish iterations)": 3 * per_device(unit)
        + (2 + 2 * 3.5 + 1) * per_device(cube),
    }
    prof = {k: load(f"profile_{k}.json") for k in ("adamw", "soap", "gimbal")}
    if all(prof.values()):
        lines += [
            "## Optimizer update cost and its floating-point model (gate G4.3)",
            "",
            "Device time per call of each compiled update, from 20-step traces "
            "(`benchmarks/tpu/profile_step.py`, minimal trace reader "
            "`benchmarks/tpu/xplane.py`); every update includes the all-gather of the "
            "parameter increments (≈12.6 ms, identical for all optimizers).",
            "",
        ]
        for k, p in prof.items():
            mods = sorted(p["modules_ms_per_step"].items(), key=lambda kv: -kv[1])
            parts = ", ".join(f"{v:.2f} ms" for _, v in mods[1:3])
            lines.append(
                f"* {k}: gradient step {mods[0][1]:.2f} ms per step; update modules "
                f"{parts} per step (amortized over the 20 traced steps)."
            )
        lines += [
            "",
            "Floating-point model at full-precision float32 (≈37 TFLOP/s measured for "
            "the batched 2048³ products):",
            "",
            "| work | multiply-adds per device | lower bound (ms) |",
            "|---|---|---|",
        ]
        for k, v in flops.items():
            lines.append(f"| {k} | {v:.3g} | {2 * v / 37e12 * 1e3:.1f} |")
        lines += [
            "",
            "Measured optimizer work beyond the common all-gather stays within 2× of "
            "these bounds for SOAP's and Gimbal's matrix products. SOAP's QR refresh is "
            "Householder QR (XLA custom calls), which is not bound by matrix-multiply "
            "throughput; AdamW's update is memory-bound on the replicated parameters.",
            "",
        ]
    tests = RES / "tests_tpu.txt"
    if tests.exists():
        lines += [
            "## Tests on the TPU (gate G4.1)",
            "",
            "```",
            tests.read_text().strip(),
            "```",
            "",
            "Float64 comparisons run on the CPU only (no float64 on the TPU); "
            "tolerances in `tests/test_jax_optimizers.py`.",
            "",
        ]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
