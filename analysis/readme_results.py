"""Write the results block of ``README.md`` from the generated analysis files (G10.4).

Replaces the text between ``<!-- results:start -->`` and ``<!-- results:end -->`` in
``README.md`` with tables built from ``analysis/results/phase08.json`` (validation results and the
decision rule), ``runs/main/<optimizer>/seed<k>/test.json`` (the one-time test evaluation),
``analysis/results/compute.json`` and ``runs/tuning/selection.json``. Nothing is typed by hand, so
the README cannot drift from the analysis.

Usage: python analysis/readme_results.py
"""

from __future__ import annotations

import json
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
START, END = "<!-- results:start -->", "<!-- results:end -->"
OPTS = ("adamw", "soap", "gimbal")
SEEDS = (2, 3)
NAMES = {"adamw": "AdamW", "soap": "SOAP", "gimbal": "Gimbal"}
KNOB = {"adamw": "b2", "soap": "shampoo_beta", "gimbal": "rot_rate"}


def load(path: pathlib.Path):
    return json.loads(path.read_text()) if path.exists() else None


def block() -> str:
    res = load(ROOT / "analysis" / "results" / "phase08.json")
    if not res:
        return "_The confirmatory runs have not been analysed yet._"
    comp = load(ROOT / "analysis" / "results" / "compute.json") or {}
    sel = load(ROOT / "runs" / "tuning" / "selection.json") or {}
    lines = [
        "| optimizer | tuned peak lr (secondary knob) | validation loss, seeds 2 / 3 | mean "
        "(perplexity) | test loss, mean | step time (ms) | TPU v4 chip-hours (tuning + main) |",
        "|---|---|---|---|---|---|---|",
    ]
    for opt in OPTS:
        runs = [res["runs"].get(f"{opt}/seed{s}", {}) for s in SEEDS]
        vals = [r.get("val_loss") for r in runs]
        tests = [load(ROOT / "runs" / "main" / opt / f"seed{s}" / "test.json") for s in SEEDS]
        s = sel.get(opt, {})
        knob = f"{s['lr']:.3g} ({KNOB[opt]} = {s[KNOB[opt]]})" if s else "—"
        val = " / ".join("diverged" if r.get("diverged") else f"{v:.4f}" for r, v in
                         zip(runs, vals, strict=True)) if all(runs) else "—"
        ok = [v for v in vals if v is not None]
        mean = f"{sum(ok) / len(ok):.4f} ({math.exp(sum(ok) / len(ok)):.2f})" if len(ok) == 2 \
            else "—"
        tl = [t["test_loss"] for t in tests if t]
        test = f"{sum(tl) / len(tl):.4f}" if len(tl) == 2 else "—"
        st = [r.get("steady_state_step_s") for r in runs]
        step = f"{1e3 * sum(st) / len(st):.1f}" if all(st) else "—"
        ch = comp.get("total_chip_hours", {}).get(opt)
        lines.append(f"| {NAMES[opt]} | {knob} | {val} | {mean} | {test} | {step} | "
                     f"{'—' if ch is None else f'{ch:.0f}'} |")
    lines += ["", f"Pooled within-run bootstrap SE of a final validation loss: "
              f"{res['pooled_within_run_se']:.4f}; seed-to-seed SD pooled over optimizers: "
              f"{res['pooled_seed_sd']:.4f}.", ""]
    for c, p in res.get("paired", {}).items():
        diffs = ", ".join(f"{e['gimbal_minus']:+.4f}" for e in p["per_seed"].values())
        mult = [e["token_multiplier"] for e in p["per_seed"].values()]
        mtxt = (f"; tokens to reach {NAMES[c]}'s final loss: {sum(mult) / len(mult):.3f}× fewer"
                if mult and all(mult) else f"; {NAMES[c]}'s final loss not reached")
        lines.append(f"* Gimbal − {NAMES[c]} (paired by seed): {diffs} (mean {p['mean_diff']:+.4f}, "
                     f"threshold −{p['two_pooled_se']:.4f}){mtxt}. Beats on loss: "
                     f"**{'yes' if p['beats_on_loss'] else 'no'}**; on wall-clock: "
                     f"**{'yes' if p['beats_on_wallclock'] else 'no'}**.")
    dec = res.get("decision", {})
    if dec:
        lines += ["", "Predeclared headline claim (beats AdamW and SOAP on loss and is no slower "
                  "than SOAP per step): **"
                  + ("allowed" if dec["headline_claim_allowed"] else "not allowed") + "**."]
    lines += ["", "Generated by `analysis/readme_results.py` from `analysis/results/` "
              "(details: `analysis/results/phase08_tables.md`, `analysis/decision.md`)."]
    return "\n".join(lines)


def main() -> None:
    text = README.read_text()
    if START not in text or END not in text:
        raise SystemExit("README.md has no results markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    README.write_text(f"{head}{START}\n{block()}\n{END}{tail}")
    print(block())


if __name__ == "__main__":
    main()
